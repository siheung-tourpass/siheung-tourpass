-- PostgreSQL 16+ / UTC; run against an empty siheung_tourpass database.

BEGIN;
SET TIME ZONE 'UTC';
CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login_id VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  display_name VARCHAR(100) NOT NULL,
  role VARCHAR(8) NOT NULL CHECK(role IN ('VISITOR','STAFF','ADMIN')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

CREATE TABLE region (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

CREATE TABLE theme (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

CREATE TABLE companion_type (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

CREATE TABLE place (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  region_id BIGINT NOT NULL,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  location_description VARCHAR(500) NOT NULL,
  material_kind VARCHAR(8) NOT NULL CHECK(material_kind IN ('REAL','DEMO')),
  source_url VARCHAR(2048),
  checked_on DATE,
  evidence_note VARCHAR(1000) NOT NULL,
  review_status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK(review_status IN ('DRAFT','APPROVED','REJECTED')),
  reviewed_by BIGINT,
  reviewed_at TIMESTAMPTZ(6),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(reviewed_by) REFERENCES app_user(id),
  CHECK((review_status='DRAFT' AND reviewed_by IS NULL AND reviewed_at IS NULL) OR (review_status<>'DRAFT' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK(material_kind<>'DEMO' OR (source_url IS NULL AND checked_on IS NULL)),
  CHECK(material_kind<>'REAL' OR review_status<>'APPROVED' OR (source_url IS NOT NULL AND checked_on IS NOT NULL)),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(region_id) REFERENCES region(id)
);

CREATE TABLE place_source (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_id BIGINT NOT NULL,
  source_url VARCHAR(2048) NOT NULL,
  checked_on DATE NOT NULL,
  evidence_note VARCHAR(1000) NOT NULL,
  FOREIGN KEY(place_id) REFERENCES place(id)
);

CREATE TABLE place_theme (
  place_id BIGINT NOT NULL,
  theme_id BIGINT NOT NULL,
  material_kind VARCHAR(8) NOT NULL CHECK(material_kind IN ('REAL','DEMO')),
  source_url VARCHAR(2048),
  checked_on DATE,
  evidence_note VARCHAR(1000) NOT NULL,
  review_status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK(review_status IN ('DRAFT','APPROVED','REJECTED')),
  reviewed_by BIGINT,
  reviewed_at TIMESTAMPTZ(6),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(reviewed_by) REFERENCES app_user(id),
  CHECK((review_status='DRAFT' AND reviewed_by IS NULL AND reviewed_at IS NULL) OR (review_status<>'DRAFT' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK(material_kind<>'DEMO' OR (source_url IS NULL AND checked_on IS NULL)),
  CHECK(material_kind<>'REAL' OR review_status<>'APPROVED' OR (source_url IS NOT NULL AND checked_on IS NOT NULL)),
  PRIMARY KEY(place_id,theme_id),
  FOREIGN KEY(place_id) REFERENCES place(id),
  FOREIGN KEY(theme_id) REFERENCES theme(id)
);

CREATE TABLE place_companion (
  place_id BIGINT NOT NULL,
  companion_type_id BIGINT NOT NULL,
  material_kind VARCHAR(8) NOT NULL CHECK(material_kind IN ('REAL','DEMO')),
  source_url VARCHAR(2048),
  checked_on DATE,
  evidence_note VARCHAR(1000) NOT NULL,
  review_status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK(review_status IN ('DRAFT','APPROVED','REJECTED')),
  reviewed_by BIGINT,
  reviewed_at TIMESTAMPTZ(6),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(reviewed_by) REFERENCES app_user(id),
  CHECK((review_status='DRAFT' AND reviewed_by IS NULL AND reviewed_at IS NULL) OR (review_status<>'DRAFT' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK(material_kind<>'DEMO' OR (source_url IS NULL AND checked_on IS NULL)),
  CHECK(material_kind<>'REAL' OR review_status<>'APPROVED' OR (source_url IS NOT NULL AND checked_on IS NOT NULL)),
  PRIMARY KEY(place_id,companion_type_id),
  FOREIGN KEY(place_id) REFERENCES place(id),
  FOREIGN KEY(companion_type_id) REFERENCES companion_type(id)
);

CREATE TABLE theme_parent (
  child_theme_id BIGINT NOT NULL,
  parent_theme_id BIGINT NOT NULL,
  material_kind VARCHAR(8) NOT NULL CHECK(material_kind IN ('REAL','DEMO')),
  source_url VARCHAR(2048),
  checked_on DATE,
  evidence_note VARCHAR(1000) NOT NULL,
  review_status VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK(review_status IN ('DRAFT','APPROVED','REJECTED')),
  reviewed_by BIGINT,
  reviewed_at TIMESTAMPTZ(6),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(reviewed_by) REFERENCES app_user(id),
  CHECK((review_status='DRAFT' AND reviewed_by IS NULL AND reviewed_at IS NULL) OR (review_status<>'DRAFT' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK(material_kind<>'DEMO' OR (source_url IS NULL AND checked_on IS NULL)),
  CHECK(material_kind<>'REAL' OR review_status<>'APPROVED' OR (source_url IS NOT NULL AND checked_on IS NOT NULL)),
  PRIMARY KEY(child_theme_id,parent_theme_id),
  FOREIGN KEY(child_theme_id) REFERENCES theme(id),
  FOREIGN KEY(parent_theme_id) REFERENCES theme(id),
  CHECK(child_theme_id<>parent_theme_id)
);

CREATE TABLE merchant (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  place_id BIGINT NOT NULL,
  name VARCHAR(100) NOT NULL,
  location_description VARCHAR(500) NOT NULL,
  demo_only BOOLEAN NOT NULL DEFAULT TRUE CHECK(demo_only=TRUE),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(place_id) REFERENCES place(id)
);

CREATE TABLE merchant_staff (
  user_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY(user_id,merchant_id),
  FOREIGN KEY(user_id) REFERENCES app_user(id),
  FOREIGN KEY(merchant_id) REFERENCES merchant(id)
);

CREATE TABLE product (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(1000) NOT NULL,
  duration_hours INT NOT NULL DEFAULT 24 CHECK(duration_hours=24),
  demo_only BOOLEAN NOT NULL DEFAULT TRUE CHECK(demo_only=TRUE),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

CREATE TABLE benefit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  product_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(1000) NOT NULL,
  benefit_type VARCHAR(12) NOT NULL CHECK(benefit_type IN ('FREE_ONCE','DISCOUNT')),
  use_limit INT NOT NULL DEFAULT 1 CHECK(use_limit=1),
  base_price_won INT,
  discount_won INT,
  payable_won INT NOT NULL CHECK(payable_won>=0),
  reservation_required BOOLEAN NOT NULL DEFAULT FALSE CHECK(reservation_required=FALSE),
  reservation_note VARCHAR(500) NOT NULL,
  demo_only BOOLEAN NOT NULL DEFAULT TRUE CHECK(demo_only=TRUE),
  CHECK((benefit_type='FREE_ONCE' AND base_price_won IS NULL AND discount_won IS NULL AND payable_won=0) OR (benefit_type='DISCOUNT' AND base_price_won IS NOT NULL AND discount_won IS NOT NULL AND base_price_won>=0 AND discount_won>=0 AND discount_won<=base_price_won AND payable_won=base_price_won-discount_won)),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(product_id) REFERENCES product(id),
  FOREIGN KEY(merchant_id) REFERENCES merchant(id)
);

CREATE TABLE issued_pass (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  code VARCHAR(32) NOT NULL UNIQUE,
  product_name VARCHAR(100) NOT NULL,
  duration_hours INT NOT NULL DEFAULT 24 CHECK(duration_hours=24),
  starts_at TIMESTAMPTZ(6) NOT NULL,
  expires_at TIMESTAMPTZ(6) NOT NULL,
  demo_only BOOLEAN NOT NULL DEFAULT TRUE CHECK(demo_only=TRUE),
  cancelled_at TIMESTAMPTZ(6),
  cancelled_by BIGINT,
  cancel_reason VARCHAR(500),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(owner_id) REFERENCES app_user(id),
  FOREIGN KEY(product_id) REFERENCES product(id),
  FOREIGN KEY(cancelled_by) REFERENCES app_user(id),
  CHECK(expires_at=(starts_at + INTERVAL '24 hours')),
  CHECK((cancelled_at IS NULL AND cancelled_by IS NULL AND cancel_reason IS NULL) OR (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL AND CHAR_LENGTH(TRIM(cancel_reason)) BETWEEN 1 AND 500))
);

CREATE TABLE issued_benefit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pass_id BIGINT NOT NULL,
  benefit_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  place_id BIGINT NOT NULL,
  merchant_name VARCHAR(100) NOT NULL,
  place_name VARCHAR(100) NOT NULL,
  region_name VARCHAR(100) NOT NULL,
  location_description VARCHAR(500) NOT NULL,
  benefit_name VARCHAR(100) NOT NULL,
  description VARCHAR(1000) NOT NULL,
  benefit_type VARCHAR(12) NOT NULL CHECK(benefit_type IN ('FREE_ONCE','DISCOUNT')),
  use_limit INT NOT NULL DEFAULT 1 CHECK(use_limit=1),
  base_price_won INT,
  discount_won INT,
  payable_won INT NOT NULL CHECK(payable_won>=0),
  reservation_required BOOLEAN NOT NULL DEFAULT FALSE CHECK(reservation_required=FALSE),
  reservation_note VARCHAR(500) NOT NULL,
  demo_only BOOLEAN NOT NULL DEFAULT TRUE CHECK(demo_only=TRUE),
  CHECK((benefit_type='FREE_ONCE' AND base_price_won IS NULL AND discount_won IS NULL AND payable_won=0) OR (benefit_type='DISCOUNT' AND base_price_won IS NOT NULL AND discount_won IS NOT NULL AND base_price_won>=0 AND discount_won>=0 AND discount_won<=base_price_won AND payable_won=base_price_won-discount_won)),
  remaining_count INT NOT NULL DEFAULT 1 CHECK(remaining_count IN (0,1)),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(pass_id) REFERENCES issued_pass(id),
  FOREIGN KEY(benefit_id) REFERENCES benefit(id),
  FOREIGN KEY(merchant_id) REFERENCES merchant(id),
  FOREIGN KEY(place_id) REFERENCES place(id),
  UNIQUE(pass_id,benefit_id)
);

CREATE TABLE redemption (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issued_benefit_id BIGINT NOT NULL UNIQUE,
  staff_user_id BIGINT NOT NULL,
  used_at TIMESTAMPTZ(6) NOT NULL,
  FOREIGN KEY(issued_benefit_id) REFERENCES issued_benefit(id),
  FOREIGN KEY(staff_user_id) REFERENCES app_user(id)
);

CREATE TABLE feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  redemption_id BIGINT NOT NULL UNIQUE,
  rating INT NOT NULL CHECK(rating BETWEEN 1 AND 5),
  comment VARCHAR(500),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(redemption_id) REFERENCES redemption(id)
);

CREATE TABLE feedback_reason (
  feedback_id BIGINT NOT NULL,
  reason_code VARCHAR(16) NOT NULL CHECK(reason_code IN ('INTEREST','COMPANION_FIT','COST','GUIDANCE')),
  PRIMARY KEY(feedback_id,reason_code),
  FOREIGN KEY(feedback_id) REFERENCES feedback(id) ON DELETE CASCADE
);

CREATE TABLE feedback_theme (
  feedback_id BIGINT NOT NULL,
  theme_id BIGINT NOT NULL,
  PRIMARY KEY(feedback_id,theme_id),
  FOREIGN KEY(feedback_id) REFERENCES feedback(id) ON DELETE CASCADE,
  FOREIGN KEY(theme_id) REFERENCES theme(id)
);

CREATE TABLE ontology_revision (
  id INT PRIMARY KEY CHECK(id=1),
  revision BIGINT NOT NULL DEFAULT 1 CHECK(revision>=1)
);

CREATE TABLE journey (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL,
  name VARCHAR(100) NOT NULL,
  travel_date DATE,
  status VARCHAR(10) NOT NULL DEFAULT 'PLANNING' CHECK(status IN ('PLANNING','CONFIRMED','ARCHIVED')),
  issued_pass_id BIGINT,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY(owner_id) REFERENCES app_user(id),
  FOREIGN KEY(issued_pass_id) REFERENCES issued_pass(id)
);

CREATE TABLE journey_place (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journey_id BIGINT NOT NULL,
  place_id BIGINT,
  card_kind VARCHAR(8) NOT NULL CHECK(card_kind IN ('PLACE','EVENT','MERCHANT')),
  card_key VARCHAR(150) NOT NULL,
  position INT NOT NULL CHECK(position>=1),
  place_name VARCHAR(100) NOT NULL,
  region_name VARCHAR(100) NOT NULL,
  location_description VARCHAR(500) NOT NULL,
  material_kind VARCHAR(8) NOT NULL CHECK(material_kind IN ('REAL','DEMO')),
  visited_on DATE,
  note VARCHAR(500),
  rating INT CHECK(rating BETWEEN 1 AND 5),
  CHECK(rating IS NULL OR visited_on IS NOT NULL),
  FOREIGN KEY(journey_id) REFERENCES journey(id),
  FOREIGN KEY(place_id) REFERENCES place(id),
  CHECK((card_kind='PLACE')=(place_id IS NOT NULL)),
  UNIQUE(journey_id,card_key),
  UNIQUE(journey_id,place_id)
);

CREATE TABLE journey_pass_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journey_id BIGINT NOT NULL,
  issued_pass_id BIGINT NOT NULL,
  linked_at TIMESTAMPTZ(6),
  disconnected_at TIMESTAMPTZ(6),
  CHECK(linked_at IS NULL OR disconnected_at IS NULL OR disconnected_at>=linked_at),
  FOREIGN KEY(journey_id) REFERENCES journey(id),
  FOREIGN KEY(issued_pass_id) REFERENCES issued_pass(id)
);

CREATE INDEX place_region_id_active_review_status_id_idx ON place(region_id,active,review_status,id);
CREATE INDEX place_theme_theme_id_place_id_idx ON place_theme(theme_id,place_id);
CREATE INDEX place_companion_companion_type_id_place_id_idx ON place_companion(companion_type_id,place_id);
CREATE INDEX theme_parent_parent_theme_id_child_theme_id_idx ON theme_parent(parent_theme_id,child_theme_id);
CREATE INDEX merchant_staff_merchant_id_user_id_idx ON merchant_staff(merchant_id,user_id);
CREATE INDEX issued_pass_owner_id_cancelled_at_expires_at_idx ON issued_pass(owner_id,cancelled_at,expires_at);
CREATE INDEX issued_benefit_merchant_id_id_idx ON issued_benefit(merchant_id,id);
CREATE INDEX redemption_used_at_id_idx ON redemption(used_at,id);
CREATE INDEX feedback_theme_theme_id_feedback_id_idx ON feedback_theme(theme_id,feedback_id);
CREATE INDEX journey_owner_id_status_id_idx ON journey(owner_id,status,id);
CREATE INDEX journey_place_journey_id_position_id_idx ON journey_place(journey_id,position,id);
CREATE INDEX journey_pass_history_journey_id_id_idx ON journey_pass_history(journey_id,id);

-- Keep modification timestamps for every table that owns updated_at.
CREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD THEN NEW.updated_at = clock_timestamp(); END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER app_user_updated_at BEFORE UPDATE ON app_user FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER region_updated_at BEFORE UPDATE ON region FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER theme_updated_at BEFORE UPDATE ON theme FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER companion_type_updated_at BEFORE UPDATE ON companion_type FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER place_updated_at BEFORE UPDATE ON place FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER place_theme_updated_at BEFORE UPDATE ON place_theme FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER place_companion_updated_at BEFORE UPDATE ON place_companion FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER theme_parent_updated_at BEFORE UPDATE ON theme_parent FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER merchant_updated_at BEFORE UPDATE ON merchant FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER product_updated_at BEFORE UPDATE ON product FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER benefit_updated_at BEFORE UPDATE ON benefit FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER feedback_updated_at BEFORE UPDATE ON feedback FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER journey_updated_at BEFORE UPDATE ON journey FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

COMMIT;
