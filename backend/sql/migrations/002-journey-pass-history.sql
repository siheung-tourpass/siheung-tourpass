BEGIN;
SET TIME ZONE 'UTC';
CREATE TABLE journey_pass_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journey_id BIGINT NOT NULL,
  issued_pass_id BIGINT NOT NULL,
  linked_at TIMESTAMPTZ(6),
  disconnected_at TIMESTAMPTZ(6),
  CHECK(linked_at IS NULL OR disconnected_at IS NULL OR disconnected_at>=linked_at),
  FOREIGN KEY(journey_id) REFERENCES journey(id),
  FOREIGN KEY(issued_pass_id) REFERENCES issued_pass(id)
);

-- The original link time was not recorded; preserve it as unknown.
INSERT INTO journey_pass_history(journey_id,issued_pass_id)
SELECT id,issued_pass_id FROM journey WHERE issued_pass_id IS NOT NULL;

CREATE INDEX journey_pass_history_journey_id_id_idx ON journey_pass_history(journey_id,id);

COMMIT;
